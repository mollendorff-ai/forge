#!/usr/bin/env bash
# Write the Homebrew formula for a released version of Forge to standard output.
#
#   scripts/homebrew-formula.sh 10.0.0-rc.11 checksums.txt > Formula/forge.rb
#
# checksums.txt is the file the Release workflow attaches to each GitHub
# release (`sha256  dir/forge-<target>.tar.gz` per line). The formula installs
# the prebuilt binary of that release; this repository is its tap:
#
#   brew tap mollendorff-ai/forge https://github.com/mollendorff-ai/forge
#   brew install mollendorff-ai/forge/forge
set -euo pipefail

version="${1:?usage: homebrew-formula.sh VERSION CHECKSUMS_FILE}"
checksums="${2:?usage: homebrew-formula.sh VERSION CHECKSUMS_FILE}"
base="https://github.com/mollendorff-ai/forge/releases/download/v${version}"

sha() {
  local target="$1" found
  found=$(awk -v f="forge-${target}.tar.gz" '{ n = split($2, p, "/"); if (p[n] == f) print $1 }' "$checksums")
  if [[ ! "$found" =~ ^[0-9a-f]{64}$ ]]; then
    echo "homebrew-formula.sh: no sha256 for forge-${target}.tar.gz in ${checksums}" >&2
    exit 1
  fi
  echo "$found"
}

mac_arm=$(sha aarch64-apple-darwin)
mac_intel=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-musl)
linux_intel=$(sha x86_64-unknown-linux-musl)

cat <<EOF
# Generated by scripts/homebrew-formula.sh from the checksums of the release.
# The Release workflow rewrites it after each release; do not edit it by hand.
class Forge < Formula
  desc "Git-native financial modeling in YAML"
  homepage "https://mollendorff.ai/forge"
  version "${version}"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "${base}/forge-aarch64-apple-darwin.tar.gz"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "${base}/forge-x86_64-apple-darwin.tar.gz"
      sha256 "${mac_intel}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/forge-aarch64-unknown-linux-musl.tar.gz"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${base}/forge-x86_64-unknown-linux-musl.tar.gz"
      sha256 "${linux_intel}"
    end
  end

  def install
    bin.install "forge"
  end

  test do
    assert_match "forge #{version}", shell_output("#{bin}/forge --version")
  end
end
EOF
